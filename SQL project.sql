SELECT 
    PRODUCT_REF,
    PRODUCT_NAME,
    SUPPLIER_int,
    UNITS_ON_ORDER,
    UNIT_PRICE, QUANTITY
FROM PRODUCTS
WHERE 
    QUANTITY LIKE '%bottles%'
    AND SUBSTRING(PRODUCT_NAME, 3, 1) IN ('t', 'T')
    AND SUPPLIER_int IN (1, 2, 3, 7) -- j'ai ajouté 7 pour vérifier la requête, si non pas de résultat
    AND UNIT_PRICE BETWEEN 70 AND 200
    AND UNITS_ON_ORDER IS NOT NULL;

