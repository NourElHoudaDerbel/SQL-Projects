SELECT DISTINCT 
    S.SUPPLIER_int AS [Supplier Number],
    S.COMPANY,
    S.ADDRESS,
    S.PHONE
FROM SUPPLIERS S
JOIN PRODUCTS P ON S.SUPPLIER_int = P.SUPPLIER_int
JOIN CATEGORIES C ON P.CATEGORY_CODE = C.CATEGORY_CODE
WHERE C.CATEGORY_NAME = 'Beverages';

--6
SELECT C.CUSTOMER_CODE
FROM CUSTOMERS C
LEFT JOIN ORDERS O ON C.CUSTOMER_CODE = O.CUSTOMER_CODE
LEFT JOIN ORDER_DETAILS OD ON O.ORDER_int = OD.ORDER_int
LEFT JOIN PRODUCTS P ON OD.PRODUCT_REF = P.PRODUCT_REF
LEFT JOIN CATEGORIES CAT ON P.CATEGORY_CODE = CAT.CATEGORY_CODE
WHERE C.CITY = 'Berlin'
GROUP BY C.CUSTOMER_CODE
HAVING COUNT(CASE WHEN CAT.CATEGORY_NAME = 'Desserts' THEN 1 END) <= 1;

--7
SELECT 
    C.CUSTOMER_CODE AS [Customer Number],
    C.COMPANY AS [Company Name],
    C.PHONE,
    ISNULL(SUM(OD.UNIT_PRICE * OD.QUANTITY * (1 - OD.DISCOUNT)), 0) AS [Total Amount],
    C.COUNTRY
FROM CUSTOMERS C
LEFT JOIN ORDERS O 
    ON C.CUSTOMER_CODE = O.CUSTOMER_CODE 
    AND O.ORDER_DATE BETWEEN '1998-04-01' AND '1998-04-30'
    AND DATEPART(WEEKDAY, O.ORDER_DATE) = 2
LEFT JOIN ORDER_DETAILS OD ON O.ORDER_int = OD.ORDER_int
WHERE C.COUNTRY = 'France'
GROUP BY 
    C.CUSTOMER_CODE, C.COMPANY, C.PHONE, C.COUNTRY;

--8

SELECT 
    C.CUSTOMER_CODE,
    C.COMPANY AS [Company Name],
    C.PHONE AS [Telephone Number]
FROM CUSTOMERS C
JOIN ORDERS O ON C.CUSTOMER_CODE = O.CUSTOMER_CODE
JOIN ORDER_DETAILS OD ON O.ORDER_int = OD.ORDER_int
GROUP BY C.CUSTOMER_CODE, C.COMPANY, C.PHONE
HAVING COUNT(DISTINCT OD.PRODUCT_REF) = (SELECT COUNT(*) FROM PRODUCTS);


--9

SELECT 
    C.CUSTOMER_CODE,
    COUNT(O.ORDER_int) AS [Number of Orders]
FROM CUSTOMERS C
LEFT JOIN ORDERS O ON C.CUSTOMER_CODE = O.CUSTOMER_CODE
WHERE C.COUNTRY = 'France'
GROUP BY C.CUSTOMER_CODE, C.COMPANY;


