SELECT
    EMPLOYEE_int,
    FIRST_NAME,
    LAST_NAME,
    DATEDIFF(YEAR, BIRTH_DATE, GETDATE()) AS Age,
    DATEDIFF(YEAR, HIRE_DATE, GETDATE()) AS Seniority
FROM EMPLOYEES
WHERE 
    TITLE IN ('Mr.', 'Dr.')
    AND (SALARY + ISNULL(COMMISSION, 0)) >= 8000
ORDER BY 
    Seniority DESC;

