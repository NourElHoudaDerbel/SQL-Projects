SELECT *
FROM CUSTOMERS
WHERE 
    COUNTRY = (SELECT COUNTRY FROM SUPPLIERS WHERE SUPPLIER_int = 1)
    AND CITY = (SELECT CITY FROM SUPPLIERS WHERE SUPPLIER_int = 1)
    AND RIGHT(POSTAL_CODE, 3) = RIGHT((SELECT POSTAL_CODE FROM SUPPLIERS WHERE SUPPLIER_int = 1), 3);

